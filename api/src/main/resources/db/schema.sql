CREATE TABLE COCHE_TIPO (
    ID                          VARCHAR(50)    PRIMARY KEY,
    NOMBRE                      VARCHAR(50)    NOT NULL,
    PRECIO_BASE                 NUMERIC(10,2)  NOT NULL DEFAULT 0 CHECK (PRECIO_BASE >= 0),
    PUNTOS_LEALTAD              INT            NOT NULL DEFAULT 0 CHECK (PUNTOS_LEALTAD >= 0)
);

